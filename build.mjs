// Generates the consumable forms from src/: a Tailwind v3 preset, a Tailwind v4
// theme stylesheet, and plain CSS classes for projects without Tailwind (Vue,
// Astro, anything without a Tailwind build). Same class names in every shape, so
// markup copied between projects keeps working.
//
// src/ holds two kinds of source. colors.css, type.json and theme.json are
// extracted from the console by scripts/extract.mjs and must not be hand-edited.
// kit.css and kit.json are authored: the plivo.com theme kit the console has not
// adopted yet. The build layers the kit over the extraction.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { readFile } from 'node:fs/promises'

const src = (name) => new URL(`src/${name}`, import.meta.url)
const read = async (name) => JSON.parse(await readFile(src(name), 'utf8'))
const [extractedType, theme, meta, kit] = await Promise.all([
  read('type.json'),
  read('theme.json'),
  read('meta.json'),
  read('kit.json'),
])

/** The kit adds names; it never silently redefines an extracted one. A clash
    means upstream adopted a kit token, and the kit copy should be deleted. */
const layer = (base, extra, what) => {
  const clash = Object.keys(extra).filter((k) => k in base)
  if (clash.length) throw new Error(`kit.json redefines extracted ${what}: ${clash.join(', ')}`)
  return { ...base, ...extra }
}
const type = layer(extractedType, kit.type, 'type tokens')
const colors = layer(theme.colors, kit.colors, 'colours')

mkdirSync(new URL('dist/', import.meta.url), { recursive: true })

const lines = [
  '@plivo/tokens — generated by build.mjs, do not edit.',
  `Extracted from Plivo's design system on ${meta.extractedAt}, with the plivo.com kit layered on top.`,
]
const cssBanner = `/* ${lines.join('\n   ')} */`
const jsBanner = lines.map((l) => `// ${l}`).join('\n')

/** Tailwind wants [size, { lineHeight, fontWeight, ... }]; family and transform
    have no home in that tuple, so they only survive into the CSS builds. */
const fontSize = Object.fromEntries(
  Object.entries(type).map(([name, t]) => [
    name,
    [
      t.size,
      {
        lineHeight: t.line,
        fontWeight: String(t.weight),
        ...(t.tracking ? { letterSpacing: t.tracking } : {}),
        ...(t.style ? { fontStyle: t.style } : {}),
      },
    ],
  ])
)

writeFileSync(
  new URL('dist/tailwind.cjs', import.meta.url),
  `${jsBanner}
module.exports = {
  theme: {
    extend: ${JSON.stringify({ colors, borderRadius: theme.borderRadius, fontFamily: theme.fontFamily, fontSize }, null, 6).replace(/\n/g, '\n    ')},
  },
}
`
)

// A family name with a space must be quoted in CSS; the source arrays are bare.
const stack = (key) =>
  theme.fontFamily[key]?.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', ')

// Family is chosen by role, not repeated per token: Sora for display sizes,
// JetBrains Mono for labels, kickers, CTAs and stats, Inter for everything
// else. Each goes through its own var so a host can swap a face without
// touching the ramp.
const role = (name, t) => {
  if (t.family === 'jetbrains') return 'mono'
  if (t.family === 'sora' || /^(h[1-4]|xl)-/.test(name)) return 'display'
  return 'sans'
}
const familyVar = (name, t) =>
  ({
    mono: 'var(--font-mono, ui-monospace, monospace)',
    display: 'var(--font-display, var(--font-sans, system-ui, sans-serif))',
    sans: 'var(--font-sans, system-ui, sans-serif)',
  })[role(name, t)]

const rule = (name, t) =>
  [
    `.text-${name} {`,
    `  font-size: ${t.size};`,
    `  line-height: ${t.line};`,
    `  font-weight: ${t.weight};`,
    t.tracking && `  letter-spacing: ${t.tracking};`,
    t.style && `  font-style: ${t.style};`,
    `  font-family: ${familyVar(name, t)};`,
    t.transform && `  text-transform: ${t.transform};`,
    t.numeric && `  font-variant-numeric: ${t.numeric};`,
    '}',
  ]
    .filter(Boolean)
    .join('\n')

/* The class form only helps consumers that control the markup. A library
   styling its own elements needs custom properties, so emit both: a `font`
   shorthand per token (weight size/line family) plus tracking, which the
   shorthand cannot carry. */
const fontVar = (name, t) =>
  `  --text-${name}: ${t.style ? `${t.style} ` : ''}${t.weight} ${t.size}/${t.line} ${familyVar(
    name,
    t
  )};${t.tracking ? `\n  --text-${name}-tracking: ${t.tracking};` : ''}`

const familyVars = [
  `  --font-sans: ${stack('inter')};`,
  `  --font-display: ${stack('sora')};`,
  `  --font-mono: ${stack('jetbrains')};`,
].join('\n')

writeFileSync(
  new URL('dist/type.css', import.meta.url),
  `${cssBanner}

:root {
${familyVars}

${Object.entries(type).map(([n, t]) => fontVar(n, t)).join('\n')}
}

${Object.entries(type).map(([n, t]) => rule(n, t)).join('\n\n')}
`
)

/* Tailwind v4 reads its theme from CSS, not from a JS preset. Colours go in a
   plain `inline` block so var(--color-*) also works in hand-written CSS. Radius
   and type go in `inline reference`: utilities only, no emitted variables —
   --radius would otherwise be declared as itself, and --text-<name> would
   collide with type.css, which uses those names for `font` shorthands. */
// DEFAULT first: JS enumerates integer-like keys (surface's "2") ahead of it.
const v4Colors = Object.entries(colors).flatMap(([name, value]) =>
  typeof value === 'string'
    ? [[name, value]]
    : Object.entries(value)
        .sort(([a], [b]) => (b === 'DEFAULT') - (a === 'DEFAULT'))
        .map(([k, v]) => [k === 'DEFAULT' ? name : `${name}-${k}`, v])
)
// v4 has two named steps v3 lacks (xs, 4xl); one corner everywhere means they
// map to the same token. `none` and `full` are built in, so they stay out.
const v4Radii = [
  ...new Set([...Object.keys(theme.borderRadius), 'xs', '4xl'].filter((k) => !['none', 'full'].includes(k))),
].map((k) => (k === 'DEFAULT' ? '--radius' : `--radius-${k}`))
const v4Text = Object.entries(type).flatMap(([name, t]) =>
  [
    `  --text-${name}: ${t.size};`,
    `  --text-${name}--line-height: ${t.line};`,
    `  --text-${name}--font-weight: ${t.weight};`,
    t.tracking && `  --text-${name}--letter-spacing: ${t.tracking};`,
  ].filter(Boolean)
)
// Only role tokens name a family. A body token that also set font-family would
// sort after `font-mono` and silently undo it; body text inherits Inter instead.
const v4Extras = Object.entries(type)
  .map(([name, t]) => {
    const decls = [
      role(name, t) !== 'sans' && `  font-family: var(--font-${role(name, t)});`,
      t.style && `  font-style: ${t.style};`,
      t.transform && `  text-transform: ${t.transform};`,
      t.numeric && `  font-variant-numeric: ${t.numeric};`,
    ].filter(Boolean)
    return decls.length ? `@utility text-${name} {\n${decls.join('\n')}\n}` : null
  })
  .filter(Boolean)

writeFileSync(
  new URL('dist/tailwind.css', import.meta.url),
  `${cssBanner}

/* Tailwind v4: @import this after "tailwindcss", alongside colors.css for the
   values. Dark mode is the .dark class; declare the variant to match:
   @custom-variant dark (&:where(.dark, .dark *)); */

@theme inline {
${v4Colors.map(([n, v]) => `  --color-${n}: ${v};`).join('\n')}
}

@theme inline reference {
${v4Radii.map((n) => `  ${n}: var(--radius);`).join('\n')}

${v4Text.join('\n')}
}

@theme {
${familyVars}
  --font-jetbrains: ${stack('jetbrains')};
  --font-inter: ${stack('inter')};
  --font-sora: ${stack('sora')};
}

${v4Extras.join('\n\n')}
`
)

writeFileSync(
  new URL('dist/colors.css', import.meta.url),
  `${readFileSync(src('colors.css'), 'utf8')}\n${readFileSync(src('kit.css'), 'utf8')}`
)
writeFileSync(new URL('dist/type.json', import.meta.url), `${JSON.stringify(type, null, 2)}\n`)

console.log(
  `built ${Object.keys(type).length} type classes + ${Object.keys(colors).length} colour groups (kit: ${
    Object.keys(kit.type).length
  } type, ${Object.keys(kit.colors).length} colour)`
)
